import Foundation

extension String {
  enum ProductIdentifier {
    static let monthly = "bloom_pro_monthly"
    static let yearly = "bloom_pro_yearly"
    static let monthlyHalf = "bloom_499_1m"
    static let yearlyHalf = "bloom_1999_1y_3d0"
    static let weeklyLower = "bloom_149_1w"
    static let monthlyLower = "bloom_399_1m"
    static let yearlyLower = "bloom_2999_1y_7d0"
  }
}
